// Builds Pages/Shared/_Icons.cshtml: an inline SVG sprite from Lucide icons (ISC licence).
// Use in Razor:  <svg class="icon" aria-hidden="true"><use href="#i-truck"></use></svg>
// Add an icon: put its Lucide name in the map below and run `node scripts/build-icons.mjs`.
import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const icons = {
  truck: 'truck', package: 'package', store: 'store', globe: 'globe', card: 'credit-card',
  phone: 'smartphone', cash: 'banknote', bag: 'shopping-bag', moon: 'moon', sun: 'sun',
  heart: 'heart', home: 'house', tag: 'tag', snowflake: 'snowflake', gift: 'gift', close: 'x',
  minus: 'minus', plus: 'plus', trash: 'trash-2', chevron: 'chevron-right', pin: 'map-pin',
  leaf: 'leaf', flame: 'flame', sparkles: 'sparkles', arrow: 'arrow-right', info: 'info',
  check: 'check', lock: 'lock', mail: 'mail', call: 'phone',
};
let out = '@* Generated by ClientApp/scripts/build-icons.mjs from Lucide (https://lucide.dev, ISC licence). Do not edit by hand. *@\n';
out += '<svg xmlns="http://www.w3.org/2000/svg" style="display:none" aria-hidden="true">\n';
for (const [id, name] of Object.entries(icons)) {
  const svg = await readFile(path.join(here, '../node_modules/lucide-static/icons', `${name}.svg`), 'utf8');
  const inner = svg.replace(/^[\s\S]*?<svg[^>]*>/, '').replace(/<\/svg>\s*$/, '').replace(/\s*\n\s*/g, '');
  out += `  <symbol id="i-${id}" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="1.6" stroke-linecap="round" stroke-linejoin="round">${inner}</symbol>\n`;
}
// Instagram-style camera glyph (drawn by hand; Lucide no longer ships brand icons).
out += '  <symbol id="i-instagram" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="1.6" stroke-linecap="round" stroke-linejoin="round"><rect x="3" y="3" width="18" height="18" rx="5"/><circle cx="12" cy="12" r="4"/><circle cx="17.5" cy="6.5" r="0.6" fill="currentColor"/></symbol>\n';
// Brand mark: drop above a bowl (simplified from the Candle Obsession logo).
out += '  <symbol id="i-logo" viewBox="0 0 64 64"><path d="M32 4 C32 4 22 18 22 24.5 a10 10 0 0 0 20 0 C42 18 32 4 32 4Z" fill="#F2BE84"/><path d="M7 38.5c0-3 2.4-5 5.5-4.8 7.2.4 13 2.4 17.8 5.6-6.4 3.4-14.5 4.2-22.4 2.3C7.3 41.4 7 40 7 38.5Z" fill="#D48F49"/><path d="M9 44.5c9.5 2.4 19.8.8 27.6-4.8 5.2-3.7 10.5-6.3 16.6-6.6 2.8-.1 4.8 1.9 4.8 4.6v1.6C58 51 46.4 61 32.5 61 20.6 61 10.7 53.9 9 44.5Z" fill="#B37428"/></symbol>\n';
out += '</svg>\n';
await writeFile(path.resolve(here, '../../Pages/Shared/_Icons.cshtml'), out);
console.log(`✓ ${Object.keys(icons).length + 2} icons`);
